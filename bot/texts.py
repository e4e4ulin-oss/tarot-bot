def topic_label(key: str | None) -> str:
    if not key:
        return "не указана"
    return TOPICS.get(key, key)


def plural_followups(count: int) -> str:
    """«1 вопрос», «2 вопроса», «5 вопросов» — иначе фраза читается как машинная."""
    tail = count % 100
    if 11 <= tail <= 14:
        word = "вопросов"
    elif count % 10 == 1:
        word = "вопрос"
    elif count % 10 in (2, 3, 4):
        word = "вопроса"
    else:
        word = "вопросов"
    return f"{count} {word}"


def genitive_hours(count: int) -> str:
    """Родительный падеж: «в течение 1 часа», «до 2 часов»."""
    word = "часа" if count % 10 == 1 and count % 100 != 11 else "часов"
    return f"{count} {word}"


def short(text: str, limit: int = 120) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def esc(text: str | None) -> str:
    return escape(text) if text else ""
